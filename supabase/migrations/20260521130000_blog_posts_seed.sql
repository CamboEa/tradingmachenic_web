សិស្ស Trading Machenic ត្រូវបានណែនាំឲ្យជ្រើស **មួយសម័យសំខាន់** ក្នុងមួយថ្ងៃ—មិនមែនបីសម័យទាំងអស់។

## អាស៊ី៖ រៀបចំ មិនមែនប្រកួត (សម្រាប់អ្នកជាច្រើន)

សម្រាប់អ្នករៀននៅកម្ពុជា (UTC+7) សម័យអាស៊ីគួរប្រើសម្រាប់៖

- កំណត់កម្រិត H4/D1
- កត់ត្រាពេលវេលាព័ត៌មានសំខាន់
- កំណត់ alert—មិន market order ពេលសារធារណៈរឹមរឹលរាយ

បើធ្វើពាណិជ្ជកម្មអាស៊ី ត្រូវមានវិន័យច្បាស់។ បើមិនដូច្នោះ អ្នកហាត់ភាពចៃដន្យ។

## ឡុងដ្ឋាន៖ ការពង្រីមជួរ

សង្កេត៖

- ការលុបកម្រិត high/low សម័យមុន
- ការទទួលយកលើស/ក្រោមជួរច្បាស់
- ភាពសមស្របជាមួយ DXY និងទិន្នផល ១០Y (បរិបទ)

**ឧទាហរណ៍វិន័យ៖** មិនបន្ថែមហានិភ័យក្នុង ៥ នាទីដំប឴ងបន្ទាប់ពី spike ខ្លាំង លុះត្រាតែផែនការកំណត់រួចហើយ។

## ញូវយ៉ក៖ បញ្ជាក់ ឬជំទាប់

ទិន្នន័យអាមេរិកអាចបង្កើនល្បឿន ឬបង្កើត **ជំទាប់ព័ត៌មាន**។ ទម្លាប់មានប្រយោជន៍៖

- តូចទំហំមុន CPI, FOMC, NFP
- រង់ចាំ candle បិទដំបូងបន្ទាប់ទិន្នន័យ
- បើឡុងដ្ឋាន និងញូវយ៉កមិនដូចគ្នា ឲ្យអាទិភាពពេលវេលាខ្ពស់ជាង

