## Why sessions matter on gold

XAU/USD is global, but liquidity is not constant. The **London open** frequently establishes the day’s first serious directional attempt. The **New York open** can confirm, fade, or reverse that attempt when U.S. participants and data releases enter.

Trading Machenic students are encouraged to pick **one primary window** per day—not all three sessions.

## Asia: preparation, not performance (for many traders)

For Cambodia-based learners on UTC+7, the Asia window is often best used to:

- Mark higher-timeframe levels (H4/D1)
- Note scheduled red-folder times for the day
- Set alerts—not market orders on thin liquidity

If you trade Asia, define rules explicitly. Otherwise you are practicing randomness.

## London: expansion and structure breaks

Watch for:

- Sweep of prior session high/low
- Acceptance above/below a well-defined range
- Correlation with DXY and U.S. 10Y yields (context, not gospel)

**Rule example:** No new risk in the first five minutes after a violent spike unless your plan already defined that scenario.

## New York: confirmation or trap

U.S. data can accelerate moves or produce **headline traps**—sharp spikes that revert within an hour. Useful habits:

- Reduce size into CPI, FOMC, and NFP windows
- Let the first post-data candle close before committing size
- If London and New York disagree, favor the higher-timeframe bias

## Journal prompts (copy into your log)

- Which session produced the cleanest structure today?
- Did I trade my chosen window or drift?
- Was gold moving with yields, with the dollar, or on its own story?

## Key takeaways

- Assign yourself one primary session; mastery beats coverage
- London often sets tone; New York often tests conviction
- Data days are risk-management days first, opportunity days second
