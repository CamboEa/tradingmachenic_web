## Volatility is information—not a signal

When daily ranges widen, beginners often react in one of two ways: they freeze, or they chase. Professionals treat wider ranges as **higher variance**, not as permission to increase size. The math is simple—if your stop distance must widen to respect structure, your position size should usually shrink so that dollar risk stays constant.

## The three numbers you must know

Before any XAU/USD or major FX idea, write these down:

- **Account risk cap** — e.g. 0.5%–1.0% per trade for learning accounts
- **Stop distance** — in points or pips, tied to structure, not hope
- **Lot size** — output of the formula, not a round “nice” number

If you cannot state all three in one sentence, you are not ready to execute.

## Pre-trade checklist (60 seconds)

- Is this trade A+ setup or boredom?
- Did I mark session context (Asia / London / New York)?
- Is news within the next 30 minutes? If yes, reduce size or stand down
- Is correlated exposure already open (e.g. long gold + long AUD)?
- Where is invalidation—and what changes my mind?

## After the trade

Discipline continues after entry. Log:

- Planned risk vs. actual slippage
- Whether you moved the stop early for emotion
- Screenshot of the chart at decision time

Over twenty trades, patterns appear. That is the compounding edge—**not** a hotter indicator.

## Key takeaways

- Wider ranges demand smaller size if dollar risk is fixed
- Checklists remove debate in fast markets
- Review logs weekly; size rules evolve with your data
